// Решение о показе экрана победы.
//
// Дефект, ради которого этот модуль появился (§3.9 / §10.8 (E) отчёта задачи 31):
// `world.victory_achieved` выставляется движком один раз и **никогда не сбрасывается**
// (`engine/mod.rs:618`), а `App.tsx` рендерил `VictoryScreen` прямо по этому флагу.
// Полноэкранный оверлей поэтому возвращался на каждом рендере, а его кнопка
// «Продолжить наблюдение» была подключена к `onContinue={() => {}}` — пустой функции.
// В rome `balanced` победа наступает на тике 33, и оставшиеся 117 полугодий партии
// игрок не мог увидеть в принципе.
//
// Решение (названо явно, оно не единственное возможное): оверлей показывается
// **один раз за партию** — при первом рендере после победы, — и после того как игрок
// его закрыл, в этой партии больше не появляется. Альтернатива «показывать каждый раз,
// пока не закрыт навсегда» отвергнута: она отличается от дефекта только наличием
// кнопки, а флаг движка остаётся истинным вечно.
//
// Признак «партия» — не идентификатор, а точки, в которых мир заменяется целиком:
// старт сценария и загрузка сохранения. В обеих флаг сбрасывается, иначе победа
// в следующей партии не была бы показана.

/** Состояние показа оверлея. Живёт только в UI, в мир не пишется. */
export interface VictoryOverlayState {
  /** Игрок закрыл оверлей победы в текущей партии. */
  dismissed: boolean;
}

/** Начальное состояние: ничего не закрыто. Оно же — состояние новой партии. */
export const initialVictoryOverlayState: VictoryOverlayState = { dismissed: false };

/**
 * Показывать ли оверлей сейчас.
 *
 * `victoryAchieved` приходит из `WorldState` и после победы истинен всегда,
 * поэтому один он решением быть не может — второй аргумент и есть то, чего
 * не хватало.
 */
export function shouldShowVictoryOverlay(
  victoryAchieved: boolean | undefined,
  state: VictoryOverlayState,
): boolean {
  return Boolean(victoryAchieved) && !state.dismissed;
}

/** Игрок нажал «Продолжить наблюдение». */
export function dismissVictoryOverlay(_state: VictoryOverlayState): VictoryOverlayState {
  return { dismissed: true };
}

/** Мир заменён целиком (старт сценария или загрузка сохранения). */
export function resetVictoryOverlay(): VictoryOverlayState {
  return initialVictoryOverlayState;
}
